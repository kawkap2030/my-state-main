/**
 * Self-host Google Fonts (Lexend + Source Sans 3) for offline Tauri builds.
 *
 * Reads the Google Fonts CSS2 response from /tmp/gfonts.css (fetched with a
 * modern woff2-capable UA), downloads every unique .woff2 file into
 * public/fonts/, and writes public/fonts/fonts.css with @font-face rules that
 * point to those local files (keeping unicode-range subsets).
 *
 * Run:  node download_fonts.cjs
 */
const fs = require('fs');
const path = require('path');
const https = require('https');

const SRC_CSS = process.argv[2] || path.join(__dirname, 'gfonts_temp.css');
const OUT_DIR = path.join(__dirname, 'public', 'fonts');

if (!fs.existsSync(SRC_CSS)) {
  console.error(`Missing source CSS: ${SRC_CSS}`);
  process.exit(1);
}

const css = fs.readFileSync(SRC_CSS, 'utf8');

// ── Parse @font-face blocks ─────────────────────────────────────────
const blocks = css.match(/@font-face\s*\{[^}]+\}/g) || [];
if (!blocks.length) {
  console.error('No @font-face blocks found — is the CSS woff2-capable?');
  process.exit(1);
}

const urlMap = new Map(); // remote url -> local filename
let fileIndex = 0;

function localNameFor(remoteUrl, family) {
  const ext = path.extname(new URL(remoteUrl).pathname) || '.woff2';
  const base = family.replace(/[^a-z0-9]+/gi, '').toLowerCase();
  return `${base}-${fileIndex++}${ext}`;
}

function rewriteBlock(block) {
  const familyMatch = block.match(/font-family:\s*'([^']+)'/);
  const family = familyMatch ? familyMatch[1] : 'Unknown';

  return block.replace(
    /url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g,
    (m, remoteUrl) => {
      if (!urlMap.has(remoteUrl)) {
        urlMap.set(remoteUrl, localNameFor(remoteUrl, family));
      }
      return `url(./${urlMap.get(remoteUrl)})`;
    }
  );
}

const rewrittenBlocks = blocks.map(rewriteBlock);

// ── Download unique fonts ───────────────────────────────────────────
function download(url, dest) {
  return new Promise((resolve, reject) => {
    https
      .get(url, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
        if (res.statusCode !== 200) {
          reject(new Error(`HTTP ${res.statusCode} for ${url}`));
          res.resume();
          return;
        }
        const file = fs.createWriteStream(dest);
        res.pipe(file);
        file.on('finish', () => file.close(resolve));
        file.on('error', reject);
      })
      .on('error', reject);
  });
}

(async () => {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const results = [];
  for (const [remoteUrl, local] of urlMap) {
    const dest = path.join(OUT_DIR, local);
    if (fs.existsSync(dest) && fs.statSync(dest).size > 1000) {
      results.push(`SKIP  ${local}`);
      continue;
    }
    await download(remoteUrl, dest);
    results.push(`OK    ${local}  (${fs.statSync(dest).size} bytes)`);
  }

  // ── Write local fonts.css ────────────────────────────────────────
  const outCss = `/* Self-hosted fonts — Lexend + Source Sans 3 (offline, no Google Fonts).
   Generated by download_fonts.cjs from the Google Fonts CSS2 API. */
${rewrittenBlocks.join('\n')}
`;
  fs.writeFileSync(path.join(OUT_DIR, 'fonts.css'), outCss);

  console.log(results.join('\n'));
  console.log(`\nWrote ${path.join(OUT_DIR, 'fonts.css')} with ${rewrittenBlocks.length} @font-face rules (${urlMap.size} files).`);
})().catch((e) => {
  console.error('FAILED:', e.message);
  process.exit(1);
});
